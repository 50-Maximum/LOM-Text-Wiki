def clean(t):
    for a, b in PAIRS:
        t = t.replace(a, b)
    t = t.replace('给赵活', '').replace('向赵活', '')
    t = t.replace('赵活', '')
    t = re.sub(r'^[，、·]+', '', t)
    t = re.sub(r'[，、]{2,}', '，', t)
    t = t.replace('。。', '。').strip()
    # 删词后残留的介词收尾（夜送料理给 / 与 等）
    while t and t[-1] in '给为与和向对替帮':
        t = t[:-1].rstrip('，、')
    return t


def main():
    db = sqlite3.connect(os.path.join(BASE, 'data', 'wiki.db'))
    rows = list(db.execute("select script,title from scenes where title is not null and title != ''"))
    fixes = {}
    changed = []
    for sc, t in rows:
        new = TITLE_FIX.get(sc)
        if new is None and '赵活' in t:
            new = clean(t)
            if not new:
                new = t
        if new and new != t:
            fixes[sc] = new
            changed.append((sc, t, new))
    json.dump(fixes, open(os.path.join(BASE, 'data', 'title_fix2.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    with open(os.path.join(BASE, '_out9.txt'), 'w', encoding='utf-8') as f:
        f.write('修订 %d 条\n' % len(fixes))
        for sc, t, n in changed:
            f.write('%-28s %s  →  %s\n' % (sc, t, n))
    # 地点表
    json.dump(PLACE_FIX, open(os.path.join(BASE, 'data', 'place_fix_stage.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    print('titles fixed', len(fixes), 'places', len(PLACE_FIX))


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    main()
